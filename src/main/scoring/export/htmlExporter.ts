/**
 * Escape HTML special characters
 */
function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/**
 * Format date range
 */
function formatDateRange(start: string, end: string): string {
  const startDate = new Date(start);
  const endDate = new Date(end);

  const options: Intl.DateTimeFormatOptions = {
    month: "short",
    day: "numeric",
    year: "numeric",
  };

  if (start === end) {
    return startDate.toLocaleDateString("en-US", options);
  }

  return `${startDate.toLocaleDateString("en-US", options)} - ${endDate.toLocaleDateString("en-US", options)}`;
}

/**
 * Format distance in km
 */
function formatDistance(meters: number): string {
  return (meters / 1000).toFixed(2);
}

/**
 * Format time as HH:MM:SS
 */
function formatTime(seconds: number | null): string {
  if (seconds === null || seconds <= 0) return "-";

  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);

  if (hours > 0) {
    return `${hours}:${String(minutes).padStart(2, "0")}:${String(secs).padStart(2, "0")}`;
  }
  return `${minutes}:${String(secs).padStart(2, "0")}`;
}

/**
 * Format points with decimal places
 */
function formatPoints(points: number, decimals: number): string {
  return points.toFixed(decimals);
}

/**
 * Generate HTML string (for preview without saving)
 */
export function generateHtmlPreview(
  competition: Competition,
  competitionResult: CompetitionResult,
  taskResults: TaskResult[],
  includeStandings: boolean,
  includeTaskResults: boolean
): string {
  const participantMap = new Map<number, Participant>();
  for (const p of competition.participants) {
    participantMap.set(p.id, p);
  }

  const taskNameMap = new Map<string, string>();
  for (const t of competition.tasks) {
    taskNameMap.set(t.id, t.name);
  }

  return generateHtml(
    competition,
    competitionResult,
    taskResults,
    participantMap,
    taskNameMap,
    includeStandings,
    includeTaskResults,
    1
  );
}
